"""Developer & Code Agent tools: Git automation, Python syntax/lint checks, and project scaffolding (ported from Mark-LVI code_helper.py & dev_agent.py)."""

from __future__ import annotations

import ast
from pathlib import Path
import subprocess
from typing import Dict, List, Optional

from tools.file_ops import atomic_write_text, resolve_user_path
from tools.registry import action


@action(
    name="git_ops",
    description="Run fast Git operations (`status`, `diff`, `log`, `branch`) in a repository directory.",
    parameters={"operation": "Optional[str]", "repo_path": "Optional[str]"},
)
def git_ops(operation: str = "status", repo_path: str = ".") -> str:
    op = (operation or "status").strip().lower()
    cwd = resolve_user_path(repo_path) if repo_path and repo_path != "." else Path(__file__).resolve().parent.parent

    cmd_map: Dict[str, List[str]] = {
        "status": ["git", "status", "-s", "-b"],
        "diff": ["git", "diff", "--stat"],
        "log": ["git", "log", "-n", "5", "--oneline"],
        "branch": ["git", "branch", "-a"],
    }
    cmd = cmd_map.get(op, ["git", "status", "-s", "-b"])
    try:
        res = subprocess.run(
            cmd,
            cwd=str(cwd),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=5.0,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0x08000000),
        )
        out = (res.stdout or res.stderr or "").strip()
        return f"status=done action=git_ops op={op} output={out!r}"
    except Exception as exc:
        return f"status=failed action=git_ops reason=\"{exc}\""


@action(
    name="inspect_python_code",
    description="Parse and validate a Python source file for syntax errors, functions, and classes.",
    parameters={"path": "str"},
)
def inspect_python_code(path: str = "") -> str:
    target = resolve_user_path(path)
    if not target.is_file():
        return f"status=failed action=inspect_python_code reason=\"File not found: {target}\""
    try:
        src = target.read_text(encoding="utf-8")
        tree = ast.parse(src, filename=str(target))
        funcs = [n.name for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
        classes = [n.name for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]
        return (
            f"status=done action=inspect_python_code path=\"{target.name}\" syntax=valid "
            f"classes={classes!r} functions={funcs[:20]!r}"
        )
    except SyntaxError as syn:
        return (
            f"status=failed action=inspect_python_code path=\"{target.name}\" "
            f"syntax_error=\"Line {syn.lineno}: {syn.msg}\""
        )
    except Exception as exc:
        return f"status=failed action=inspect_python_code reason=\"{exc}\""


@action(
    name="scaffold_project",
    description="Scaffold a clean starter project directory with entrypoint and README.",
    parameters={"name": "str", "base_dir": "Optional[str]", "language": "Optional[str]"},
)
def scaffold_project(name: str = "new_app", base_dir: str = "workspace/projects", language: str = "python") -> str:
    proj_name = (name or "new_app").strip().replace(" ", "_")
    root = resolve_user_path(base_dir) / proj_name
    root.mkdir(parents=True, exist_ok=True)

    lang = (language or "python").strip().lower()
    if lang == "python":
        entry = root / "main.py"
        atomic_write_text(
            entry,
            f'#!/usr/bin/env python3\n"""Entrypoint for {proj_name}."""\n\n\ndef main() -> None:\n    print("Hello from {proj_name}!")\n\n\nif __name__ == "__main__":\n    main()\n',
        )
    else:
        entry = root / "index.js"
        atomic_write_text(entry, f'// Entrypoint for {proj_name}\nconsole.log("Hello from {proj_name}!");\n')

    readme = root / "README.md"
    atomic_write_text(readme, f"# {proj_name}\n\nGenerated by AETHER Developer Agent.\n")
    return f"status=done action=scaffold_project root=\"{root}\" entry=\"{entry.name}\""
